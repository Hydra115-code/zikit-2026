begin;

create table if not exists public.challenge_predictions (
    id bigint generated by default as identity primary key,
    run_id varchar(64) not null,
    tenant varchar(30) not null check (tenant = 'kaiku'),
    signal_timestamp timestamptz not null,
    alert_timestamp timestamptz not null,
    alert_type varchar(30) not null check (
        alert_type in ('incident_risk', 'data_quality_alert')
    ),
    risk_score double precision not null check (risk_score between 0 and 1),
    suspected_incident_type varchar(80),
    model_version varchar(100) not null,
    policy_version varchar(100) not null,
    model_sha256 varchar(64) not null check (length(model_sha256) = 64),
    policy_sha256 varchar(64) not null check (length(policy_sha256) = 64),
    data_quality varchar(30) not null,
    context_known_event boolean not null default false,
    evidence jsonb not null,
    recommended_action text not null,
    incident_id varchar(36) references public.incidents(id) on delete cascade,
    event_id bigint not null unique references public.events(id) on delete cascade,
    created_at timestamptz not null default now(),
    constraint challenge_predictions_time_order check (
        alert_timestamp >= signal_timestamp
    ),
    constraint challenge_predictions_incident_kind check (
        (alert_type = 'incident_risk' and incident_id is not null)
        or (alert_type = 'data_quality_alert' and incident_id is null)
    ),
    constraint uq_challenge_prediction_identity unique (
        run_id,
        tenant,
        alert_timestamp,
        alert_type,
        model_version,
        policy_version
    )
);

create index if not exists ix_challenge_predictions_run_id
    on public.challenge_predictions(run_id);
create index if not exists ix_challenge_predictions_tenant
    on public.challenge_predictions(tenant);
create index if not exists ix_challenge_predictions_signal_timestamp
    on public.challenge_predictions(signal_timestamp);
create index if not exists ix_challenge_predictions_alert_timestamp
    on public.challenge_predictions(alert_timestamp);
create index if not exists ix_challenge_predictions_alert_type
    on public.challenge_predictions(alert_type);
create index if not exists ix_challenge_predictions_incident_id
    on public.challenge_predictions(incident_id);
create index if not exists ix_challenge_predictions_event_id
    on public.challenge_predictions(event_id);
create index if not exists ix_challenge_predictions_created_at
    on public.challenge_predictions(created_at);
create index if not exists ix_challenge_predictions_tenant_timeline
    on public.challenge_predictions(tenant, alert_timestamp desc);

alter table public.challenge_predictions enable row level security;

do $$
declare
    role_name text;
begin
    foreach role_name in array array['anon', 'authenticated'] loop
        if exists (select 1 from pg_roles where rolname = role_name) then
            execute format(
                'revoke all privileges on table public.challenge_predictions from %I',
                role_name
            );
            execute format(
                'revoke all privileges on all sequences in schema public from %I',
                role_name
            );
        end if;
    end loop;
end
$$;

comment on table public.challenge_predictions is
    'Durable predictions from causal replay of the official synthetic Zikit dataset.';
comment on column public.challenge_predictions.recommended_action is
    'Operator recommendation only; persistence does not imply execution.';

commit;
