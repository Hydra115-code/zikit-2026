begin;

create table if not exists public.resource_metrics (
    id bigint generated by default as identity primary key,
    source_id varchar(100) not null,
    timestamp timestamptz not null,
    cpu_percent double precision not null check (cpu_percent between 0 and 100),
    cpu_count integer not null check (cpu_count > 0),
    load_1m double precision not null check (load_1m >= 0),
    load_5m double precision not null check (load_5m >= 0),
    load_15m double precision not null check (load_15m >= 0),
    load_per_cpu double precision not null check (load_per_cpu >= 0),
    memory_total_bytes bigint not null check (memory_total_bytes >= 0),
    memory_available_bytes bigint not null check (memory_available_bytes >= 0),
    memory_percent double precision not null check (memory_percent between 0 and 100),
    disk_path varchar(500) not null,
    disk_total_bytes bigint not null check (disk_total_bytes >= 0),
    disk_free_bytes bigint not null check (disk_free_bytes >= 0),
    disk_percent double precision not null check (disk_percent between 0 and 100),
    network_rx_bytes bigint not null check (network_rx_bytes >= 0),
    network_tx_bytes bigint not null check (network_tx_bytes >= 0),
    network_rx_errors bigint not null check (network_rx_errors >= 0),
    network_tx_errors bigint not null check (network_tx_errors >= 0),
    process_count integer not null check (process_count >= 0),
    containerized boolean not null default false,
    cgroup_memory_current_bytes bigint,
    cgroup_memory_limit_bytes bigint,
    cgroup_memory_percent double precision,
    cgroup_cpu_quota_cores double precision,
    cgroup_cpu_percent double precision check (
        cgroup_cpu_percent is null or cgroup_cpu_percent between 0 and 100
    ),
    anomalous boolean not null default false,
    reasons jsonb not null default '[]'::jsonb,
    constraint resource_metrics_reasons_array check (jsonb_typeof(reasons) = 'array')
);

create index if not exists ix_resource_metrics_source_id
    on public.resource_metrics(source_id);
create index if not exists ix_resource_metrics_timestamp
    on public.resource_metrics(timestamp desc);
create index if not exists ix_resource_metrics_anomalous
    on public.resource_metrics(anomalous);
create index if not exists ix_resource_metrics_source_timestamp
    on public.resource_metrics(source_id, timestamp desc);

alter table public.resource_metrics enable row level security;

do $$
declare
    role_name text;
begin
    foreach role_name in array array['anon', 'authenticated'] loop
        if exists (select 1 from pg_roles where rolname = role_name) then
            execute format(
                'revoke all privileges on table public.resource_metrics from %I',
                role_name
            );
        end if;
    end loop;
end
$$;

comment on table public.resource_metrics is
    'Host and container resource observations collected without privileged shell execution.';

commit;
