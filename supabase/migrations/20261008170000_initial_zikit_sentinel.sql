begin;

create table if not exists public.experiments (
    id varchar(36) primary key,
    mode varchar(20) not null check (mode in ('automatic', 'manual')),
    status varchar(30) not null,
    scenario jsonb not null,
    created_at timestamptz not null default now(),
    completed_at timestamptz,
    result jsonb,
    constraint experiments_scenario_object check (jsonb_typeof(scenario) = 'object'),
    constraint experiments_result_object check (result is null or jsonb_typeof(result) = 'object')
);

create table if not exists public.incidents (
    id varchar(36) primary key,
    service varchar(100) not null,
    severity varchar(20) not null,
    status varchar(30) not null,
    first_signal_at timestamptz not null,
    detected_at timestamptz not null,
    recovered_at timestamptz,
    evidence jsonb not null default '{}'::jsonb,
    experiment_id varchar(36) references public.experiments(id) on delete set null,
    constraint incidents_evidence_object check (jsonb_typeof(evidence) = 'object'),
    constraint incidents_time_order check (detected_at >= first_signal_at),
    constraint incidents_recovery_order check (recovered_at is null or recovered_at >= detected_at)
);

create table if not exists public.events (
    id bigint generated by default as identity primary key,
    incident_id varchar(36) references public.incidents(id) on delete cascade,
    experiment_id varchar(36) references public.experiments(id) on delete set null,
    event_type varchar(40) not null,
    process_id varchar(36) not null,
    timestamp timestamptz not null default now(),
    monotonic_seconds double precision not null check (monotonic_seconds >= 0),
    details jsonb not null default '{}'::jsonb,
    constraint events_details_object check (jsonb_typeof(details) = 'object')
);

create table if not exists public.investigations (
    id bigint generated by default as identity primary key,
    incident_id varchar(36) not null references public.incidents(id) on delete cascade,
    created_at timestamptz not null default now(),
    provider varchar(30) not null,
    diagnosis text not null
);

create table if not exists public.services (
    name varchar(100) primary key,
    active boolean not null default false,
    healthy boolean not null default true,
    updated_at timestamptz not null default now()
);

create table if not exists public.metrics (
    id bigint generated by default as identity primary key,
    service varchar(100) not null references public.services(name) on delete cascade,
    timestamp timestamptz not null,
    latency_ms double precision not null check (latency_ms >= 0),
    status_code integer check (status_code is null or status_code between 100 and 599),
    timed_out boolean not null default false,
    success boolean not null
);

create table if not exists public.actions (
    id bigint generated by default as identity primary key,
    incident_id varchar(36) not null references public.incidents(id) on delete cascade,
    runbook varchar(100) not null,
    state varchar(30) not null,
    started_at timestamptz not null default now(),
    completed_at timestamptz,
    details jsonb not null default '{}'::jsonb,
    constraint actions_details_object check (jsonb_typeof(details) = 'object'),
    constraint actions_time_order check (completed_at is null or completed_at >= started_at)
);

create index if not exists ix_experiments_status on public.experiments(status);
create index if not exists ix_incidents_service on public.incidents(service);
create index if not exists ix_incidents_status on public.incidents(status);
create index if not exists ix_incidents_experiment_id on public.incidents(experiment_id);
create index if not exists ix_events_incident_id on public.events(incident_id);
create index if not exists ix_events_experiment_id on public.events(experiment_id);
create index if not exists ix_events_event_type on public.events(event_type);
create index if not exists ix_events_process_id on public.events(process_id);
create index if not exists ix_events_timeline on public.events(incident_id, monotonic_seconds);
create index if not exists ix_investigations_incident_id on public.investigations(incident_id);
create index if not exists ix_services_active on public.services(active);
create index if not exists ix_metrics_service on public.metrics(service);
create index if not exists ix_metrics_timestamp on public.metrics(timestamp);
create index if not exists ix_metrics_success on public.metrics(success);
create index if not exists ix_metrics_service_timestamp on public.metrics(service, timestamp desc);
create index if not exists ix_actions_incident_id on public.actions(incident_id);
create index if not exists ix_actions_state on public.actions(state);

alter table public.experiments enable row level security;
alter table public.incidents enable row level security;
alter table public.events enable row level security;
alter table public.investigations enable row level security;
alter table public.services enable row level security;
alter table public.metrics enable row level security;
alter table public.actions enable row level security;

do $$
declare
    role_name text;
begin
    foreach role_name in array array['anon', 'authenticated'] loop
        if exists (select 1 from pg_roles where rolname = role_name) then
            execute format(
                'revoke all privileges on table public.experiments, public.incidents, public.events, public.investigations, public.services, public.metrics, public.actions from %I',
                role_name
            );
            execute format(
                'revoke all privileges on all sequences in schema public from %I',
                role_name
            );
        end if;
    end loop;
end
$$;

comment on table public.metrics is 'Raw HTTP observations collected by Zikit Sentinel.';
comment on table public.events is 'UTC audit events plus process-scoped monotonic time.';
comment on table public.actions is 'Allowlisted runbook executions; no arbitrary commands.';

commit;
