begin;

create table if not exists public.alerts (
    id bigint generated by default as identity primary key,
    event_id bigint not null unique references public.events(id) on delete cascade,
    state varchar(20) not null default 'open' check (state in ('open', 'acknowledged')),
    priority varchar(20) not null check (priority in ('warning', 'critical', 'resolved')),
    created_at timestamptz not null default now(),
    acknowledged_at timestamptz,
    constraint alerts_acknowledgement_state check (
        (state = 'open' and acknowledged_at is null)
        or (state = 'acknowledged' and acknowledged_at is not null)
    ),
    constraint alerts_acknowledgement_order check (
        acknowledged_at is null or acknowledged_at >= created_at
    )
);

create index if not exists ix_alerts_event_id on public.alerts(event_id);
create index if not exists ix_alerts_state on public.alerts(state);
create index if not exists ix_alerts_priority on public.alerts(priority);
create index if not exists ix_alerts_created_at on public.alerts(created_at);
create index if not exists ix_alerts_state_created_at
    on public.alerts(state, created_at desc);

alter table public.alerts enable row level security;

do $$
declare
    role_name text;
begin
    foreach role_name in array array['anon', 'authenticated'] loop
        if exists (select 1 from pg_roles where rolname = role_name) then
            execute format(
                'revoke all privileges on table public.alerts from %I',
                role_name
            );
            execute format(
                'revoke all privileges on all sequences in schema public from %I',
                role_name
            );
        end if;
    end loop;
end
$$;

comment on table public.alerts is
    'Durable alert outbox derived transactionally from operational audit events.';

commit;
